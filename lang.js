// भाषा बदलण्याचे मुख्य फंक्शन (बटण क्लिक केल्यावर चालेल)
window.toggleLanguage = function() {
    let currentLang = localStorage.getItem('appLang') || 'mr';
    // जर आता मराठी असेल तर इंग्रजी करा, नाहीतर मराठी करा
    let newLang = currentLang === 'mr' ? 'en' : 'mr';
    
    // नवीन भाषा LocalStorage मध्ये सेव्ह करा
    localStorage.setItem('appLang', newLang);
    console.log("Language changed to: " + newLang);
    
    // ती भाषा पूर्ण पेजवर लागू करा
    applySavedLanguage();
};

// सेव्ह केलेली भाषा संपूर्ण पेजवर लागू करणारे फंक्शन
window.applySavedLanguage = function() {
    let currentLang = localStorage.getItem('appLang') || 'mr';
    
    // 1. Text Elements (ज्यांना data-lang हा ॲट्रिब्युट दिला आहे)
    let textElements = document.querySelectorAll('[data-lang]');
    textElements.forEach(function(el) {
        let key = el.getAttribute('data-lang');
        if (translations[currentLang] && translations[currentLang][key]) {
            el.innerHTML = translations[currentLang][key]; 
        }
    });

    // 2. Input Placeholders (ज्यांना data-lang-placeholder हा ॲट्रिब्युट दिला आहे)
    let inputElements = document.querySelectorAll('[data-lang-placeholder]');
    inputElements.forEach(function(inputEl) {
        let key = inputEl.getAttribute('data-lang-placeholder');
        if (translations[currentLang] && translations[currentLang][key]) {
            inputEl.placeholder = translations[currentLang][key]; 
        }
    });

    // 3. Select Dropdown Options (जर त्यांना data-lang दिला असेल)
    let selectOptions = document.querySelectorAll('option[data-lang]');
    selectOptions.forEach(function(optEl) {
        let key = optEl.getAttribute('data-lang');
        if (translations[currentLang] && translations[currentLang][key]) {
            optEl.innerText = translations[currentLang][key];
        }
    });
};

// जेव्हा पेज लोड होईल तेव्हा आपोआप भाषा लागू करण्यासाठी (अतिशय महत्त्वाचे!)
document.addEventListener("DOMContentLoaded", function() {
    applySavedLanguage();
});
